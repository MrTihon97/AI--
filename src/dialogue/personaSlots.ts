/**
 * Фокус последнего вопроса менеджера важнее incidental keywords в питче.
 * «…контроль администраторов… как отслеживаете конверсию?» → conversion, не admin/losses.
 */
export function questionFocusTopic(userText: string): SlotTopic | null {
  const t = userText.toLowerCase().replace(/ё/g, 'е')
  // Хвост после последнего «?»; иначе весь текст, если есть диагностический маркер
  const qMatch = t.match(/([^?]*\?)\s*$/)
  const hasDiagnostic =
    /\?/.test(t) ||
    /(подскажите|скажите|как\s+сейчас|как\s+у\s+вас|отслежива|считаете)/i.test(t)
  if (!hasDiagnostic) return null
  const focus = (qMatch?.[1] ?? t).trim()

  if (/whatsapp|ватсап|мессенджер|instagram|инстаграм/i.test(focus)) {
    return 'whatsapp'
  }
  if (/неявк|пуст.*окн|не\s+пришл/i.test(focus)) return 'no_shows'
  if (/журнал|excel|бумаг|тетрад/i.test(focus)) return 'journal'

  const sub = discoverySubIntent(focus)
  if (sub === ASK_CONVERSION_METRICS) return 'conversion'
  // Конверсия в вопросе (даже если в питче мелькнули «потери») — до admin
  if (isAskConversionMetrics(focus) && !isDiscussFinancialLosses(focus)) {
    return 'conversion'
  }
  if (sub === DISCUSS_FINANCIAL_LOSSES) return 'losses'
  if (
    /конверси|звонк\w*\s+в\s+запис|из\s+звонка\s+в\s+запис|аналитик|отслежива|дашборд|сквозн/i.test(
      focus,
    ) &&
    !isDiscussFinancialLosses(focus)
  ) {
    return 'conversion'
  }

  if (
    /обучен|онборд|саботаж|пользует\w*\s+систем|заводит\w*\s+персонал/i.test(
      focus,
    )
  ) {
    return 'admin'
  }
  if (
    /как\s+(сейчас\s+)?(напомина|ведут\s+запис|вед[её]т\s+запис|дожима|перезвон|фиксир)/i.test(
      focus,
    ) ||
    /кто\s+(вед[её]т|ведет|фиксир|отвечает).{0,24}запис/i.test(focus)
  ) {
    return 'journal'
  }
  if (/демо|zoom|слот\s+на|созвон/i.test(focus)) return 'demo'
  if (
    /сколько\s+стоит|какая\s+вилка|прайс|тариф|подписк/i.test(focus) &&
    /(₽|руб|тыс|\d)/i.test(focus)
  ) {
    return 'price'
  }
  if (/потер|теря|недозвон|слива|заявк/i.test(focus)) return 'losses'
  return null
}

function isAdminTrainingTopic(text: string): boolean {
  // «контроль администраторов» в питче ≠ топик обучения/саботажа
  return /обучен|онборд|саботаж|сопротивлени|пользует\w*\s+систем|персонал\w*\s+(не\s+)?работа|заводит\w*\s+персонал/i.test(
    text,
  )
}

/**
 * Горячие ключевые слова менеджера → топик слота
 * (цена / дорого / crm / excel / whatsapp), не случайный fallback.
 * «ДентаCRM» в представлении ≠ вопрос про CRM.
 */
export function hotKeywordTopic(userText: string): SlotTopic | null {
  const t = userText.toLowerCase().replace(/ё/g, 'е')
  if (/дорог|цен[аыуе]|стоим|прайс|бюджет|тариф|подписк/i.test(t)) {
    return 'price'
  }
  if (/whatsapp|ватсап|вотсап|мессенджер/i.test(t)) return 'whatsapp'
  if (/excel|эксель|журнал|тетрад|бумаг/i.test(t)) return 'journal'
  // Бренд компании в intro не перетягивает топик на admin/CRM
  const withoutBrand = t.replace(/дента\s*crm|дентаcrm/gi, ' ')
  if (
    /\bcrm\b|crm[- ]?систем|про\s+crm|ваш[аеу]?\s+crm|внедр\w*\s+crm/i.test(
      withoutBrand,
    )
  ) {
    return 'admin'
  }
  return null
}

export function detectTopic(
  userText: string,
  entities: string[] = [],
): SlotTopic {
  const t = userText.toLowerCase().replace(/ё/g, 'е')

  // 1) Сначала — о чём спросили в вопросе
  const qFocus = questionFocusTopic(userText)
  if (qFocus) return qFocus

  // 1b) Явные hot-keywords (возражение «дорого», «CRM», Excel…)
  const hot = hotKeywordTopic(userText)
  if (hot) return hot

  // 2) Sub-intent по всему тексту (конверсия ≠ потери)
  const sub = discoverySubIntent(userText)
  if (sub === ASK_CONVERSION_METRICS) return 'conversion'
  if (sub === DISCUSS_FINANCIAL_LOSSES) return 'losses'

  // 3) Явные темы по тексту (порядок: боль/канал → процесс → цена/слот)
  if (entities.includes('whatsapp') || /whatsapp|ватсап|мессенджер|instagram/i.test(t)) {
    return 'whatsapp'
  }
  if (entities.includes('неявки') || /неявк|пуст.*окн|не\s+пришл/i.test(t)) {
    return 'no_shows'
  }
  if (entities.includes('журнал') || /журнал|excel|бумаг|тетрад/i.test(t)) {
    return 'journal'
  }
  if (
    entities.includes('конверсия') ||
    isAskConversionMetrics(t)
  ) {
    return 'conversion'
  }
  if (
    entities.includes('потери') ||
    /потер|теря|заявк|недозвон|слива|недополуча|выручк/i.test(t)
  ) {
    return 'losses'
  }
  if (isAdminTrainingTopic(t)) {
    return 'admin'
  }
  // Голое «администратор» без обучения — только если нет сетевой/конверсионной рамки
  if (
    (entities.includes('администратор') || /админ|ирина|сотрудник/i.test(t)) &&
    !/конверси|аналитик|потер|филиал|сквозн/i.test(t)
  ) {
    return 'admin'
  }
  if (entities.includes('демо') || /демо|zoom|созвон|слот/i.test(t)) {
    return 'demo'
  }
  // ₽ в расчёте потерь/выручки — не топик «price»
  if (
    entities.includes('цена') ||
    (isSubscriptionPriceContext(t) && !isLossRevenueContext(t)) ||
    (/цен[аы]|стоим|прайс|тариф|подписк\w*\s+от\s+\d+/i.test(t) &&
      !isLossRevenueContext(t)) ||
    (/(₽|руб)/i.test(t) &&
      !isLossRevenueContext(t) &&
      (isSubscriptionPriceContext(t) ||
        /цен[аы]|стоим|прайс|тариф|подписк/i.test(t)))
  ) {
    return 'price'
  }
  return 'generic'
}
