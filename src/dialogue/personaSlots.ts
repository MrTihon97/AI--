/** Sub-intents for discovery — не смешивать метрики сети с шаблонами «потерь». */
export type DiscoverySubIntent =
  | 'ASK_CONVERSION_METRICS'
  | 'DISCUSS_FINANCIAL_LOSSES'

export const ASK_CONVERSION_METRICS = 'ASK_CONVERSION_METRICS' as const
export const DISCUSS_FINANCIAL_LOSSES = 'DISCUSS_FINANCIAL_LOSSES' as const

/** Конверсия / филиальная аналитика без явных «потерь» и денег. */
export function isAskConversionMetrics(text: string): boolean {
  const t = text.toLowerCase().replace(/ё/g, 'е')
  return /конверси|звонк\w*\s*(?:в\s+)?запис|из\s+звонка\s+в\s+запис|сквозн\w*\s+аналитик|(?:отслежива|счита)е?те.{0,32}конверси|(?:филиал|сет[ьи]|клиник).{0,56}(?:аналитик|дашборд|отч[её]т|конверси)|(?:аналитик|дашборд|отч[её]т).{0,40}(?:филиал|сет|клиник)/i.test(
    t,
  )
}

/** Явные финансовые потери / деньги / недозвон-заявки — не путать с конверсией. */
export function isDiscussFinancialLosses(text: string): boolean {
  const t = text.toLowerCase().replace(/ё/g, 'е')
  return /(потер|теря|недополуча|упущенн|выручк|слива|недозвон|пропущен|не\s+перезвон|в\s+деньг|₽|руб)/i.test(
    t,
  )
}

/**
 * ASK_CONVERSION_METRICS vs DISCUSS_FINANCIAL_LOSSES.
 * Конверсия без явных потерь/денег → conversion; иначе losses.
 */
export function discoverySubIntent(
  text: string,
): DiscoverySubIntent | null {
  const conv = isAskConversionMetrics(text)
  const loss = isDiscussFinancialLosses(text)
  if (conv && !loss) return ASK_CONVERSION_METRICS
  if (loss && !conv) return DISCUSS_FINANCIAL_LOSSES
  if (conv && loss) {
    const t = text.toLowerCase().replace(/ё/g, 'е')
    const qMatch = t.match(/([^?]*\?)\s*$/)
    const focus = (qMatch?.[1] ?? t).trim()
    if (isAskConversionMetrics(focus) && !isDiscussFinancialLosses(focus)) {
      return ASK_CONVERSION_METRICS
    }
    return DISCUSS_FINANCIAL_LOSSES
  }
  return null
}

export type PersonaSlotBank = {
  /** Короткие подтверждения «на линии» */
  lineAcks: string[]
  /** Мягкие приветствия (intro) */
  helloAcks: string[]
  /** Вопросы «о чём речь» */
  helloAsks: string[]
  /** Факты по темам боли */
  facts: Record<SlotTopic, string[]>
  /** Вопросы назад менеджеру (не на каждый ход!) */
  asks: Record<SlotTopic, string[]>
  /**
   * Завершения без вопроса — чтобы диалог не был вечным интервью.
   * Формула хода: Ack + Fact + (Ask | Statement)
   */
  statements: Record<SlotTopic, string[]>
  /** Реакции на названную цену */
  priceStatedAcks: string[]
  /** Ранний прайс — блок */
  earlyPriceAcks: string[]
  earlyPriceAsks: string[]
  /** Закрытие */
  closingAcks: string[]
  closingStatements: string[]
  closingEarlyAcks: string[]
  closingEarlyAsks: string[]
  /** Вдумчивый ответ на питч */
  pitchAcks: string[]
  pitchAsks: string[]
  pitchStatements: string[]
  /**
   * Скепсис / занятость с ClientCard.mood —
   * сомнение в цифрах и тайм-прессинг.
   */
  pushbackAcks: string[]
  pushbackAsks: string[]
  pushbackStatements: string[]
  /** Клиент озвучивает: «У нас уже есть 1С / Инфодент». */
  legacyCrmPushedAcks: string[]
  legacyCrmPushedAsks: string[]
  legacyCrmPushedStatements: string[]
  /**
   * Discovery: менеджер спросил про МИС —
   * клиент явно называет стек и уточняет «поверх vs перенос».
   */
  legacyCrmDiscoveryAcks: string[]
  legacyCrmDiscoveryFacts: string[]
  legacyCrmDiscoveryAsks: string[]
  /** Злость на предложение снести рабочую МИС. */
  replacementErrorAcks: string[]
  replacementErrorAsks: string[]
  replacementErrorStatements: string[]
  /** Интеграция ок, но нужны цифры окупаемости. */
  integrationGoodAcks: string[]
  integrationGoodAsks: string[]
  integrationGoodStatements: string[]
}

